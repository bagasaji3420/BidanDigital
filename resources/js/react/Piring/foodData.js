// ── Helper: ambil 15 item acak dengan distribusi seimbang ──
export function getRandomFoods(mode, total = 15) {
    const pool = FOODS.filter((f) => f.mode.includes(mode));

    const byZona = {
        sayur: pool.filter((f) => f.zona === "sayur"),
        karbo: pool.filter((f) => f.zona === "karbo"),
        protein: pool.filter((f) => f.zona === "protein"),
    };

    const shuffle = (arr) => [...arr].sort(() => Math.random() - 0.5);

    // Distribusi: 6 sayur/buah, 4 karbo, 5 protein
    const picked = [
        ...shuffle(byZona.sayur).slice(0, 6),
        ...shuffle(byZona.karbo).slice(0, 4),
        ...shuffle(byZona.protein).slice(0, 5),
    ];

    return shuffle(picked);
}

// ── Helper: hitung skor dari item yang sudah di-drop ──
//
// Sistem penilaian baru — lebih jelas dan adil:
//
// Skor terdiri dari 2 komponen:
//
// 1. AKURASI PENEMPATAN (70 poin maks)
//    Setiap item yang diletakkan di zona yang benar mendapat poin.
//    Setiap item di zona yang salah MENGURANGI poin.
//    Formula: (benar - salah) / total * 70  (minimal 0)
//
// 2. PROPORSI PIRING (30 poin maks)
//    Mengacu pedoman Isi Piringku Kemenkes:
//    - Sayur & buah ≥ 50% dari total item → 15 poin
//    - Karbohidrat antara 20–35% → 8 poin
//    - Protein antara 20–35% → 7 poin
//    Nilai proporsi turun secara proporsional jika meleset dari target.
//
// Bintang:
//    ⭐⭐⭐ = skor ≥ 80
//    ⭐⭐   = skor ≥ 55
//    ⭐    = skor < 55
//
export function hitungSkor(droppedItems) {
    const sayurItems   = droppedItems.sayur   ?? [];
    const karboItems   = droppedItems.karbo   ?? [];
    const proteinItems = droppedItems.protein ?? [];

    const total = sayurItems.length + karboItems.length + proteinItems.length;

    if (total === 0) return { skor: 0, bintang: 0, pesan: [] };

    // ── 1. Akurasi penempatan (0–70 poin) ──────────────────────────
    const benar = [
        ...sayurItems.filter((f) => f.zona === "sayur"),
        ...karboItems.filter((f) => f.zona === "karbo"),
        ...proteinItems.filter((f) => f.zona === "protein"),
    ].length;

    const salah = total - benar;

    // Akurasi bersih: item benar dikurangi item salah, lalu dinormalisasi
    const akurasiNet = Math.max(0, benar - salah);
    const skorAkurasi = Math.round((akurasiNet / total) * 70);

    // ── 2. Proporsi piring (0–30 poin) ─────────────────────────────
    const pSayur   = sayurItems.length / total;   // target ≥ 0.50
    const pKarbo   = karboItems.length / total;   // target 0.20–0.35
    const pProtein = proteinItems.length / total; // target 0.20–0.35

    // Sayur/buah: poin penuh jika ≥ 50%, turun proporsional jika kurang
    const poinSayur = pSayur >= 0.5
        ? 15
        : Math.round((pSayur / 0.5) * 15);

    // Karbo: poin penuh jika dalam range 20–35%
    // Jika di luar range, hitung seberapa jauh dari titik tengah range (27.5%)
    const karboIdeal = 0.275;
    const karboToleransi = 0.075; // ±7.5% dari ideal masih dapat poin penuh
    const karboSelisih = Math.abs(pKarbo - karboIdeal);
    const poinKarbo = karboSelisih <= karboToleransi
        ? 8
        : Math.max(0, Math.round(8 * (1 - (karboSelisih - karboToleransi) / karboIdeal)));

    // Protein: sama seperti karbo
    const proteinIdeal = 0.275;
    const proteinToleransi = 0.075;
    const proteinSelisih = Math.abs(pProtein - proteinIdeal);
    const poinProtein = proteinSelisih <= proteinToleransi
        ? 7
        : Math.max(0, Math.round(7 * (1 - (proteinSelisih - proteinToleransi) / proteinIdeal)));

    const skorProporsi = poinSayur + poinKarbo + poinProtein;

    // ── Total skor ──────────────────────────────────────────────────
    const skor = Math.min(100, skorAkurasi + skorProporsi);

    // ── Bintang ─────────────────────────────────────────────────────
    const bintang = skor >= 80 ? 3 : skor >= 55 ? 2 : 1;

    // ── Saran ───────────────────────────────────────────────────────
    const pesan = [];

    if (salah > 0) {
        pesan.push(`${salah} makanan diletakkan di zona yang kurang tepat — perhatikan kategori tiap makanan`);
    }
    if (pSayur < 0.5) {
        pesan.push("Sayur & buah kurang dari setengah piring — idealnya ½ piring untuk serat dan vitamin");
    }
    if (pKarbo < 0.2) {
        pesan.push("Porsi karbohidrat terlalu sedikit — butuh energi dari sumber karbo (¼ piring)");
    } else if (pKarbo > 0.35) {
        pesan.push("Porsi karbohidrat terlalu banyak — kurangi agar tidak dominan di piring");
    }
    if (pProtein < 0.2) {
        pesan.push("Porsi protein kurang — tambahkan sumber protein untuk pertumbuhan (¼ piring)");
    } else if (pProtein > 0.35) {
        pesan.push("Porsi protein terlalu banyak — seimbangkan dengan sayur dan karbo");
    }
    if (skor >= 80) {
        pesan.push("Komposisi piringmu sudah sangat seimbang dan penempatan makanannya tepat! 🎉");
    } else if (skor >= 55 && pesan.length === 0) {
        pesan.push("Hampir sempurna! Sedikit penyesuaian lagi untuk piring yang ideal.");
    }

    // Detail breakdown untuk transparansi
    const breakdown = {
        skorAkurasi,
        skorProporsi,
        benar,
        salah,
        total,
    };

    return { skor, bintang, pesan, breakdown };
}
